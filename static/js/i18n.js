const DICTS = { en, da };
let current = en;
let currentCode = 'en';

export function setLanguage(code) {
  const short = String(code || 'en').slice(0, 2).toLowerCase();
  currentCode = DICTS[short] ? short : 'en';
  current = DICTS[currentCode];
}

export function currentLanguage() {
  return currentCode;
}

export function has(key) {
  return key in current || key in en;
}

export function t(key, vars) {
  // A count of exactly 1 uses the key's '.one' form when the language has one.
  const dict = key in current ? current : en;
  const one = vars && Number(vars.n) === 1 ? dict[key + '.one'] : undefined;
  let s = one ?? dict[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
  return s;
}
